# Bab 3: Tipe Data Dasar Python

# Tipe data String
nama = "Eva"
print("Nama:", nama)
print("Tipe data:", type(nama))

# Tipe data Integer
umur = 16
print("Umur:", umur)
print("Tipe data:", type(umur))

# Tipe data Float
tinggi = 155.5
print("Tinggi:", tinggi)
print("Tipe data:", type(tinggi))

# Tipe data Boolean
status = True
print("Status:", status)
print("Tipe data:", type(status))
