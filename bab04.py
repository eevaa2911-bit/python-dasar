# Bab 4: Variable Python

# Membuat variabel
nama = "Eva"
kelas = "XI RPL"
umur = 16
sekolah = "SMK Negeri 2 Subang"

# Menampilkan variabel
print("Nama:", nama)
print("Kelas:", kelas)
print("Umur:", umur)
print("Sekolah:", sekolah)

# Mengubah nilai variabel
nama = "Eva Rahayu"

print("Nama setelah diubah:", nama)
