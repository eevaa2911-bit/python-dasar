# Bab 6: Operator Python

# Operator Aritmatika
a = 10
b = 3

print("Penjumlahan:", a + b)
print("Pengurangan:", a - b)
print("Perkalian:", a * b)
print("Pembagian:", a / b)
print("Modulus:", a % b)
print("Pangkat:", a ** b)
print("Pembagian Bulat:", a // b)

# Operator Perbandingan
print("Apakah a lebih besar dari b?", a > b)
print("Apakah a sama dengan b?", a == b)

# Operator Logika
x = True
y = False

print("AND:", x and y)
print("OR:", x or y)
print("NOT:", not x)
