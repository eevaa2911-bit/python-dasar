# Bab 9: List, Tuple, dan Set Python

# LIST
buah = ["Apel", "Mangga", "Jeruk"]
print("List buah:", buah)
print("Buah pertama:", buah[0])

buah.append("Pisang")
print("Setelah ditambah:", buah)

# TUPLE
warna = ("Merah", "Biru", "Kuning")
print("\nTuple warna:", warna)
print("Warna pertama:", warna[0])

# SET
angka = {1, 2, 3, 3, 4, 5}
print("\nSet angka:", angka)

angka.add(6)
print("Setelah ditambah:", angka)
