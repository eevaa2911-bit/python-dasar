# Mengimpor module mymath
import mymath

# Menggunakan fungsi dari module
hasil_tambah = mymath.tambah(10, 5)
hasil_kurang = mymath.kurang(10, 5)
hasil_kali = mymath.kali(10, 5)

# Menampilkan hasil
print("Hasil penjumlahan:", hasil_tambah)
print("Hasil pengurangan:", hasil_kurang)
print("Hasil perkalian:", hasil_kali)
